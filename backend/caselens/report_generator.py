"""Comprehensive Report Generator for CaseLens AI."""
import uuid
import datetime
from typing import List, Dict, Any, Optional
from backend.caselens.models import ReportExportResponse
from backend.caselens.storage import caselens_storage
from backend.caselens.case_analyzer import caselens_case_analyzer
from backend.caselens.contradiction_engine import caselens_contradiction_detector
from backend.caselens.missing_info_engine import caselens_missing_analyzer

class ReportGenerator:
    """Generates structured, professional case intelligence reports with Markdown export."""

    def generate_report(self, workspace_id: str, title: Optional[str] = None) -> ReportExportResponse:
        ws = caselens_storage.get_workspace(workspace_id)
        report_title = title or (f"{ws.name} — Comprehensive Legal Intelligence Report" if ws else "CaseLens Intelligence Report")
        docs = caselens_storage.list_documents(workspace_id)
        doc_names = [d.filename for d in docs]

        # Fetch or compute analysis
        analysis = caselens_storage.get_latest_case_analysis(workspace_id)
        if not analysis:
            analysis = caselens_case_analyzer.analyze_workspace(workspace_id)

        # Fetch or compute contradictions
        contradictions = caselens_storage.get_latest_contradictions(workspace_id)
        if not contradictions:
            contradictions = caselens_contradiction_detector.analyze_workspace(workspace_id)

        # Missing info
        missing_info = caselens_missing_analyzer.analyze(workspace_id)

        # Recent Q&A runs for evidence synthesis
        qa_runs = caselens_storage.list_qa_runs(workspace_id)

        report_id = f"RPT-{uuid.uuid4().hex[:8]}"
        created_at = datetime.datetime.now(datetime.timezone.utc).isoformat()

        # Build Markdown document
        md_lines = [
            f"# {report_title}",
            "",
            f"> **Generated by**: CaseLens AI Document Intelligence Platform  ",
            f"> **Date**: {created_at[:10]} | **Report ID**: `{report_id}` | **Workspace ID**: `{workspace_id}`  ",
            f"> **Platform Tagline**: *“Every claim has evidence. Every answer has a source.”*",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            "",
            analysis.executive_summary,
            "",
            "### Documents Analyzed",
            f"Total documents reviewed: **{len(docs)}**",
            ""
        ]

        for d in docs:
            md_lines.append(f"- **{d.filename}** ({d.file_type.upper()}, {d.page_count} pages, {d.chunk_count} chunks, SHA-256: `{d.content_hash[:16]}...`)")
        md_lines.append("")

        # Key Entities
        md_lines.extend([
            "---",
            "",
            "## 2. Identified Parties, Jurisdictions & Key Entities",
            "",
            "| Entity / Term | Category | Mentions | Source Documents | Context Snippet |",
            "| :--- | :--- | :--- | :--- | :--- |"
        ])
        for ent in analysis.parties_and_entities[:10]:
            clean_ctx = ent.sample_context.replace("|", "/").replace("\n", " ")
            md_lines.append(f"| **{ent.name}** | {ent.category} | {ent.mention_count} | {', '.join(ent.source_documents)} | `{clean_ctx}` |")
        md_lines.append("")

        # Obligations
        md_lines.extend([
            "---",
            "",
            "## 3. Important Contractual Obligations",
            "",
            "| Ref | Responsible Party | Obligation Specification | Deadline / Frequency | Source Ref |",
            "| :--- | :--- | :--- | :--- | :--- |"
        ])
        for obl in analysis.obligations:
            clean_text = obl.obligation_text.replace("|", "/").replace("\n", " ")
            cit_ref = f"{obl.source_document} (p. {obl.page_number})"
            md_lines.append(f"| `{obl.obligation_id}` | **{obl.responsible_party}** | {clean_text} | {obl.deadline_or_frequency} | {cit_ref} |")
        md_lines.append("")

        # Timeline
        md_lines.extend([
            "---",
            "",
            "## 4. Chronological Timeline of Recorded Events",
            "",
            "| Event Ref | Date | Event Description | Source Document |",
            "| :--- | :--- | :--- | :--- |"
        ])
        for evt in analysis.timeline:
            clean_desc = evt.description.replace("|", "/").replace("\n", " ")
            md_lines.append(f"| `{evt.event_id}` | **{evt.date_str}** | {clean_desc} | {evt.source_document} (p. {evt.page_number}) |")
        md_lines.append("")

        # Contradictions
        md_lines.extend([
            "---",
            "",
            "## 5. Potential Inconsistencies & Contradictions",
            ""
        ])
        if contradictions.findings:
            for c in contradictions.findings:
                md_lines.extend([
                    f"### ⚠️ {c.summary} ({c.category})",
                    f"- **Status**: `{c.status}` | **Severity**: `{c.severity.upper()}`",
                    f"- **Document A**: *{c.doc_a_name}* (Page {c.doc_a_page})",
                    f"  > “{c.doc_a_passage}”",
                    f"- **Document B**: *{c.doc_b_name}* (Page {c.doc_b_page})",
                    f"  > “{c.doc_b_passage}”",
                    f"- **Review Recommendation**: {c.review_recommendation}",
                    ""
                ])
        else:
            md_lines.append("No overt textual contradictions detected across current analyzed document versions.")
            md_lines.append("")

        # Missing Info Checklist
        md_lines.extend([
            "---",
            "",
            "## 6. Contract Completeness & Missing-Information Audit",
            "",
            f"> Template benchmark: **{missing_info.template_type.replace('_', ' ').title()}**  ",
            f"> Summary: Present: **{missing_info.present_count}** | Missing: **{missing_info.missing_count}** | Ambiguous: **{missing_info.ambiguous_count}**",
            "",
            "| Expected Clause | Category | Importance | Status | Review Observation |",
            "| :--- | :--- | :--- | :--- | :--- |"
        ])
        for chk in missing_info.checks:
            status_badge = "✅ Present" if chk.status == "present" else ("⚠️ Ambiguous" if chk.status == "ambiguous" else "❌ Missing")
            clean_note = chk.review_note.replace("|", "/")
            md_lines.append(f"| **{chk.field_name}** | {chk.category} | `{chk.expected_importance.upper()}` | {status_badge} | {clean_note} |")
        md_lines.append("")

        # Evidence Register
        md_lines.extend([
            "---",
            "",
            "## 7. Evidence Register & Verification Invariants",
            "",
            "| Finding ID | Stated Observation | Source Document | Page | Verification Status |",
            "| :--- | :--- | :--- | :--- | :--- |"
        ])
        for ev in analysis.evidence_register:
            clean_obs = ev.claim_or_observation.replace("|", "/")
            md_lines.append(f"| `{ev.finding_id}` | {clean_obs} | {ev.source_document} | p. {ev.page_number} | `{ev.verification_result}` |")
        md_lines.append("")

        # Limitations & Disclaimer
        md_lines.extend([
            "---",
            "",
            "## 8. Limitations & Methodological Disclosures",
            "",
            "- **Deterministic Source Grounding**: All passages and citations were extracted directly from user-uploaded or sample documents without ungrounded AI extrapolation.",
            "- **Non-Legal Advice**: CaseLens AI is an assistive document intelligence platform. Findings do not constitute legal advice and require review by a licensed attorney.",
            "- **Zero External Telemetry**: Uploaded document files and extracted passages remain persisted within the local SQLite storage boundary.",
            "",
            f"**End of Report — CaseLens AI `{report_id}`**"
        ])

        full_md = "\n".join(md_lines)

        report = ReportExportResponse(
            report_id=report_id,
            workspace_id=workspace_id,
            title=report_title,
            executive_summary=analysis.executive_summary,
            documents_analyzed=doc_names,
            findings_count=len(analysis.evidence_register),
            contradictions_count=len(contradictions.findings),
            markdown_content=full_md,
            created_at=created_at,
        )

        caselens_storage.save_report(report)
        return report

caselens_report_generator = ReportGenerator()
